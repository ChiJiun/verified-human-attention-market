#!/usr/bin/env node
// Deterministically exports the CampaignManager ABI from `forge build` output
// into packages/shared so the API and web app share one canonical interface
// (issue #19). CI regenerates it and fails if the committed copy drifts.
//
// Usage: node packages/contracts/scripts/export-abi.mjs [--check]

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const artifact = resolve(
  here,
  "../out/CampaignManager.sol/CampaignManager.json",
);
const target = resolve(
  here,
  "../../shared/src/contracts/campaign-manager-abi.ts",
);

const TYPE_ORDER = ["constructor", "function", "event", "error"];

function normalizeParam(param, isEvent) {
  const out = { name: param.name ?? "", type: param.type };
  if (isEvent) out.indexed = Boolean(param.indexed);
  if (param.components) {
    out.components = param.components.map((component) =>
      normalizeParam(component, false),
    );
  }
  return out;
}

function normalizeEntry(entry) {
  const isEvent = entry.type === "event";
  const out = { type: entry.type };
  if (entry.name !== undefined) out.name = entry.name;
  out.inputs = (entry.inputs ?? []).map((param) =>
    normalizeParam(param, isEvent),
  );
  if (entry.type === "function") {
    out.outputs = (entry.outputs ?? []).map((param) =>
      normalizeParam(param, false),
    );
  }
  if (entry.type === "function" || entry.type === "constructor") {
    out.stateMutability = entry.stateMutability;
  }
  if (isEvent) out.anonymous = Boolean(entry.anonymous);
  return out;
}

// Locale-independent ordering so output is identical on every machine.
function compareCodePoints(left, right) {
  if (left < right) return -1;
  if (left > right) return 1;
  return 0;
}

export function canonicalAbi(abi) {
  return abi
    .map(normalizeEntry)
    .sort(
      (left, right) =>
        TYPE_ORDER.indexOf(left.type) - TYPE_ORDER.indexOf(right.type) ||
        compareCodePoints(left.name ?? "", right.name ?? ""),
    );
}

export function render(abi) {
  return (
    "// GENERATED by packages/contracts/scripts/export-abi.mjs from `forge build`.\n" +
    "// Do not edit by hand. Regenerate after changing CampaignManager.sol.\n" +
    "export const campaignManagerAbi = " +
    JSON.stringify(canonicalAbi(abi), null, 2) +
    " as const;\n"
  );
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { abi } = JSON.parse(readFileSync(artifact, "utf8"));
  const output = render(abi);

  if (process.argv.includes("--check")) {
    const current = readFileSync(target, "utf8");
    if (current !== output) {
      const currentLines = current.split("\n");
      const outputLines = output.split("\n");
      for (
        let index = 0;
        index < Math.max(currentLines.length, outputLines.length);
        index += 1
      ) {
        if (currentLines[index] !== outputLines[index]) {
          // GitHub annotation so the first drift is visible without raw logs.
          console.log(
            `::error file=packages/shared/src/contracts/campaign-manager-abi.ts,line=${index + 1}::ABI drift: expected ${JSON.stringify(outputLines[index])} got ${JSON.stringify(currentLines[index])}`,
          );
          break;
        }
      }
      console.error(
        "CampaignManager ABI is out of date. Run: node packages/contracts/scripts/export-abi.mjs",
      );
      process.exit(1);
    }
    console.log("CampaignManager ABI is up to date.");
  } else {
    writeFileSync(target, output);
    console.log(`Wrote ${target}`);
  }
}
